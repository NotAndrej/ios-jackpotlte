"""Generate logo.h (1-bpp Apple logo) for the jackpotlte shim.

The shim is freestanding: it cannot decode an image at runtime, so the boot
logo is a static 1-bpp bitmap compiled into the loader. This script is the
(kitchen-side) generator; its output is committed.

Geometry (repeated in the generated header): measured from
/home/not_andrej/Downloads/IMG_20261108_170011203.jpg, a photo of the A8 panel
on the iOS userspace boot screen (white Apple logo over a progress bar).

Usage:
  gen_logo.py APPLE.svg OUT.h [--width 190] [--height 241]

APPLE.svg is Wikimedia's "Apple_logo_black.svg" (814x1000 canvas; the ink box
is ~788x1000, so the artwork aspect is 1.269). Needs ImageMagick (`magick`).
"""
import argparse
import os
import subprocess
import sys
import tempfile

from PIL import Image

PANEL_W = 1080        # JT_FB_WIDTH
PANEL_H = 2220        # JT_FB_HEIGHT
LOGO_CENTRE_Y = 896   # 40.4% of the panel height, see the header comment


def render(svg, width, height):
    """Rasterise the SVG's ink box to a 1-bpp PIL image of width x height."""
    with tempfile.TemporaryDirectory() as td:
        png = os.path.join(td, "logo.png")
        # Trim the empty canvas margin first so the ink box is what gets
        # scaled, then threshold at 50% (hard 1-bpp edges, no dithering).
        subprocess.run(
            ["magick", svg, "-background", "white", "-alpha", "remove",
             "-colorspace", "Gray", "-fuzz", "2%", "-trim", "+repage",
             "-filter", "Lanczos", "-resize", f"{width}x{height}!",
             "-threshold", "50%", "-monochrome", png],
            check=True)
        return Image.open(png).convert("1")


def pack(im):
    """MSB-first row-packed bits, 1 where the logo is inked."""
    w, h = im.size
    stride = (w + 7) // 8
    px = im.load()
    rows = []
    for y in range(h):
        row = bytearray(stride)
        for x in range(w):
            if px[x, y] == 0:      # mode "1": 0 = black = ink
                row[x >> 3] |= 0x80 >> (x & 7)
        rows.append(bytes(row))
    return w, h, stride, rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("svg")
    ap.add_argument("out")
    ap.add_argument("--width", type=int, default=190)
    ap.add_argument("--height", type=int, default=241)
    a = ap.parse_args()

    im = render(a.svg, a.width, a.height)
    w, h, stride, rows = pack(im)

    ys = [y for y, r in enumerate(rows) if any(r)]
    if ys[0] != 0 or ys[-1] != h - 1:
        print(f"warning: ink rows {ys[0]}..{ys[-1]} of {h} "
              f"(crop is not tight)", file=sys.stderr)

    x0 = (PANEL_W - w) // 2
    y0 = LOGO_CENTRE_Y - h // 2

    body = ["\t" + ",".join(f"0x{b:02x}" for b in r) + f",\t/* {i} */"
            for i, r in enumerate(rows)]
    with open(a.out, "w") as f:
        f.write(f"""/* SPDX-License-Identifier: MIT */
/* Apple logo for the panel, generated by gen_logo.py -- do not edit.
 *
 * Source: Wikimedia Commons "Apple_logo_black.svg" (814x1000 canvas, ink box
 * ~788x1000). Rendered ink box {w}x{h} px, 1 bpp, MSB first, each row padded
 * to {stride} bytes. Rows are packed flat (row r starts at r * LOGO_STRIDE).
 *
 * Size/placement come from the reference photo of the A8 panel on the iOS
 * userspace boot screen (IMG_20261108_170011203.jpg, 3072x4080):
 *   - the panel's active area is ~1603 photo px wide (body edge to body edge,
 *     1820 px, times the A8's 62.2 mm panel / 70.6 mm body ratio) and the
 *     logo's ink box is 279x335 photo px -> ~188x226 panel px. Rounded to
 *     {w}x{h}, which keeps the artwork aspect (1.269);
 *   - horizontal: the panel is centred, so x0 = ({PANEL_W} - {w}) / 2 = {x0};
 *   - vertical: the active area's top edge is ~227 photo px below the body's
 *     top edge (the earpiece is centred in the top bezel), which puts the
 *     logo's centre 40.4% of the way down the active area, y = {LOGO_CENTRE_Y}
 *     of {PANEL_H}; y0 = {LOGO_CENTRE_Y} - {h}/2 = {y0}.
 */
#ifndef JACKPOTLTE_LOGO_H
#define JACKPOTLTE_LOGO_H

#define LOGO_W\t\t{w}U
#define LOGO_H\t\t{h}U
#define LOGO_STRIDE\t{stride}U
#define LOGO_X\t\t{x0}
#define LOGO_Y\t\t{y0}

static const unsigned char logo_bits[LOGO_H * LOGO_STRIDE] = {{
""")
        f.write("\n".join(body))
        f.write("\n};\n\n#endif /* JACKPOTLTE_LOGO_H */\n")

    print(f"wrote {a.out}: {w}x{h} at ({x0},{y0}), {h * stride} bytes")


if __name__ == "__main__":
    sys.exit(main())